/**
 * 【沉浸浏览：每个专题最多取几条】
 * 沉浸浏览不再"全站统一取最新的 10 条"，而是按 政治 → 科技 → 财经 → 生活
 * 的顺序，每个专题各取最多这么多条，再拼成一张列表。
 *
 * 为什么要这样：原来按时间统一取前 10 条时，更新慢的专题（比如"生活"）
 * 常常一条都进不来，沉浸浏览里就只剩一两个专题。
 * 改成"每个专题都取"，四个专题就都能刷到。
 *
 * 想让某个专题多出现几条，把这个数字调大即可。
 */
