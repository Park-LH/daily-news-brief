/**
 * 取出"允许接入"的新闻源：白名单校验 + enabled 开关
 *
 * 这是"只用权威媒体"这条规则的唯一执行点：
 * 不在 AUTHORITATIVE_MEDIA 里、或 official 不为 true 的源，一律跳过。
 * 页面（app.js）只认这个函数的返回值，不再直接遍历 RSS_SOURCES。
 */
function getEnabledSources() {
  return RSS_SOURCES.filter(source => {
    if (source.enabled === false) return false;
    const media = AUTHORITATIVE_MEDIA[source.publisher];
    if (!media || media.official !== true) {
      console.warn(
        `[来源已拦截] 「${source.name}」的媒体机构「${source.publisher}」不在权威媒体白名单中，已跳过`
      );
      return false;
    }
    return true;
  });
}

/**
 * 查询某家媒体是否是权威官方媒体（供调试用：控制台里直接调用）
 * 例：isAuthoritativeMedia("中国新闻社") → true
 */
function isAuthoritativeMedia(publisher) {
  const media = AUTHORITATIVE_MEDIA[publisher];
  return !!(media && media.official === true);
}

/**
 * 【列表页：每个专题最多显示几条】
 * 列表页不再"全站统一取最新的 N 条"，而是每个专题各取最多这么多条。
 *
 * 为什么改：新增"政治"板块后，中新网这类源更新很密（约每 20~30 分钟一条），
 * 如果仍然按"全局最新 10 条"来挑，政治一口气就能把 10 个名额占掉大半，
 * 科技/财经/生活会被挤成空板块。改成"每个专题都有配额"就不会互相挤了。
 */
const MAX_NEWS_PER_CATEGORY = 4;

/**
 * 【列表页总条数的安全上限】
 * 每个专题都有配额后，正常情况不会超过 4 个专题 × 4 条 = 16 条。
 * 这个数字只是兜底，防止将来加了很多源把页面撑得过长。
 */
